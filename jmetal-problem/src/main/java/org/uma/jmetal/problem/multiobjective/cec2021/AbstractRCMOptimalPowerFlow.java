  protected AbstractRCMOptimalPowerFlow(int numberOfObjectives, String name) {
    numberOfObjectives(numberOfObjectives);
    numberOfConstraints(26);
    name(name);

    List<Double> lowerLimit = new ArrayList<>(34);
    List<Double> upperLimit = new ArrayList<>(34);
    for (int i = 0; i < 26; i++) {
      lowerLimit.add(-1.0);
      upperLimit.add(1.0);
    }
    for (int i = 26; i < 34; i++) {
      lowerLimit.add(0.0);
      upperLimit.add(1.0);
    }
    variableBounds(lowerLimit, upperLimit);
  }

  /** Holds the result of a power-flow evaluation, shared by all RCM40-RCM46 subclasses. */
  protected static final class PowerFlowResult {
    final double[] psp;
    final double[] qsp;
    final double[] delP;
    final double[] delQ;
    final double quirkyReactiveTerm;
    final double voltageDeviation;
    final double fuelCost;

    private PowerFlowResult(double[] psp, double[] qsp, double[] delP, double[] delQ,
        double quirkyReactiveTerm, double voltageDeviation, double fuelCost) {
      this.psp = psp;
      this.qsp = qsp;
      this.delP = delP;
      this.delQ = delQ;
      this.quirkyReactiveTerm = quirkyReactiveTerm;
      this.voltageDeviation = voltageDeviation;
      this.fuelCost = fuelCost;
    }
  }

  protected PowerFlowResult computePowerFlow(DoubleSolution solution) {
    double[] vr = new double[NUMBER_OF_BUSES];
    double[] vi = new double[NUMBER_OF_BUSES];
    vr[0] = 1.0;
    vi[0] = 0.0;
    for (int k = 0; k < 13; k++) {
      vr[1 + k] = solution.variables().get(k);
      vi[1 + k] = solution.variables().get(13 + k);
    }

    double[] pg = new double[NUMBER_OF_BUSES];
    double[] qg = new double[NUMBER_OF_BUSES];
    for (int k = 0; k < 4; k++) {
      pg[GENERATOR_BUSES[k]] = solution.variables().get(26 + k);
      qg[GENERATOR_BUSES[k]] = solution.variables().get(30 + k);
    }

    double[] ir = new double[NUMBER_OF_BUSES];
    double[] ii = new double[NUMBER_OF_BUSES];
    for (int i = 0; i < NUMBER_OF_BUSES; i++) {
      double sr = 0;
      double si = 0;
      for (int k = 0; k < NUMBER_OF_BUSES; k++) {
        sr += G[i][k] * vr[k] - B[i][k] * vi[k];
        si += G[i][k] * vi[k] + B[i][k] * vr[k];
      }
      ir[i] = sr;
      ii[i] = si;
    }

    double[] psp = new double[NUMBER_OF_BUSES];
    double[] qsp = new double[NUMBER_OF_BUSES];
    for (int i = 0; i < NUMBER_OF_BUSES; i++) {
      // S = V .* conj(I)
      psp[i] = vr[i] * ir[i] + vi[i] * ii[i];
      qsp[i] = vi[i] * ir[i] - vr[i] * ii[i];
    }

    double[] delP = new double[13];
    double[] delQ = new double[13];
    for (int k = 0; k < 13; k++) {
      delP[k] = psp[1 + k] - pg[1 + k] + P[1 + k];
      delQ[k] = qsp[1 + k] - qg[1 + k] + Q[1 + k];
    }

    // imag(V(1)*conj(I(2))) in 1-based MATLAB notation: imag(V[0]*conj(I[1])) here.
    double quirkyReactiveTerm = vi[0] * ir[1] - vr[0] * ii[1];

    double voltageDeviation = 0;
    for (int k = 1; k < NUMBER_OF_BUSES; k++) {
      double magnitude = Math.hypot(vr[k], vi[k]);
      voltageDeviation += Math.pow(1 - magnitude, 2);
    }

    double fuelCost = 0;
    for (int k = 0; k < FUEL_COST_BUSES.length; k++) {
      double pgk = pg[FUEL_COST_BUSES[k]];
      fuelCost += FUEL_COST_A[k] + FUEL_COST_B[k] * pgk + FUEL_COST_C[k] * pgk * pgk;
    }

    return new PowerFlowResult(psp, qsp, delP, delQ, quirkyReactiveTerm, voltageDeviation,
        fuelCost);
  }

  protected void setEqualityConstraints(DoubleSolution solution, PowerFlowResult result) {
    for (int k = 0; k < 13; k++) {
      solution.constraints()[k] = EQUALITY_CONSTRAINT_EPSILON - Math.abs(result.delP[k]);
      solution.constraints()[13 + k] = EQUALITY_CONSTRAINT_EPSILON - Math.abs(result.delQ[k]);
    }
  }

  protected static double sum(double[] values) {
    double total = 0;
    for (double value : values) {
      total += value;
    }
    return total;
  }
