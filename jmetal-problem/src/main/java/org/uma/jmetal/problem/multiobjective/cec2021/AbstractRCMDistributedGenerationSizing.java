  protected AbstractRCMDistributedGenerationSizing(int numberOfObjectives, String name) {
    numberOfObjectives(numberOfObjectives);
    numberOfConstraints(24);
    name(name);

    List<Double> lowerLimit = new ArrayList<>(28);
    List<Double> upperLimit = new ArrayList<>(28);
    for (int i = 0; i < 24; i++) {
      lowerLimit.add(-1.0);
      upperLimit.add(1.0);
    }
    for (int i = 24; i < 28; i++) {
      lowerLimit.add(0.0);
      upperLimit.add(1.0);
    }
    variableBounds(lowerLimit, upperLimit);
  }

  /** Holds the result of a power-flow evaluation, shared by all RCM36-RCM39 subclasses. */
  protected static final class PowerFlowResult {
    final double[] psp;
    final double[] qsp;
    final double phaseBalance;
    final double[] delP;
    final double[] delQ;

    private PowerFlowResult(double[] psp, double[] qsp, double phaseBalance, double[] delP,
        double[] delQ) {
      this.psp = psp;
      this.qsp = qsp;
      this.phaseBalance = phaseBalance;
      this.delP = delP;
      this.delQ = delQ;
    }
  }

  protected PowerFlowResult computePowerFlow(DoubleSolution solution) {
    double[] vr = new double[NUMBER_OF_BUSES];
    double[] vi = new double[NUMBER_OF_BUSES];
    vr[0] = 1.0;
    vi[0] = 0.0;
    vr[1] = Math.cos(4 * Math.PI / 3);
    vi[1] = Math.sin(4 * Math.PI / 3);
    vr[2] = Math.cos(2 * Math.PI / 3);
    vi[2] = Math.sin(2 * Math.PI / 3);
    for (int k = 0; k < 12; k++) {
      vr[3 + k] = solution.variables().get(k);
      vi[3 + k] = solution.variables().get(12 + k);
    }

    double[] pdg = new double[NUMBER_OF_BUSES];
    double[] qdg = new double[NUMBER_OF_BUSES];
    pdg[6] = solution.variables().get(24);
    pdg[14] = solution.variables().get(25);
    qdg[6] = solution.variables().get(26);
    qdg[14] = solution.variables().get(27);

    double[] ir = new double[NUMBER_OF_BUSES];
    double[] ii = new double[NUMBER_OF_BUSES];
    for (int i = 0; i < NUMBER_OF_BUSES; i++) {
      double sr = 0;
      double si = 0;
      for (int k = 0; k < NUMBER_OF_BUSES; k++) {
        sr += G[i][k] * vr[k] - B[i][k] * vi[k];
        si += G[i][k] * vi[k] + B[i][k] * vr[k];
      }
      ir[i] = sr;
      ii[i] = si;
    }

    double[] psp = new double[NUMBER_OF_BUSES];
    double[] qsp = new double[NUMBER_OF_BUSES];
    for (int i = 0; i < NUMBER_OF_BUSES; i++) {
      // S = V .* conj(I)
      psp[i] = vr[i] * ir[i] + vi[i] * ii[i];
      qsp[i] = vi[i] * ir[i] - vr[i] * ii[i];
    }

    double[] delP = new double[12];
    double[] delQ = new double[12];
    for (int k = 0; k < 12; k++) {
      delP[k] = psp[3 + k] - pdg[3 + k] - P[3 + k];
      delQ[k] = qsp[3 + k] - qdg[3 + k] - Q[3 + k];
    }

    // Phase-balance term: |I1+I2+I3| + |I1 + exp(j4pi/3)*I2 + exp(j2pi/3)*I3|
    double t1r = ir[0] + ir[1] + ir[2];
    double t1i = ii[0] + ii[1] + ii[2];
    double rot1r = Math.cos(4 * Math.PI / 3);
    double rot1i = Math.sin(4 * Math.PI / 3);
    double rot2r = Math.cos(2 * Math.PI / 3);
    double rot2i = Math.sin(2 * Math.PI / 3);
    double t2r = ir[0] + (rot1r * ir[1] - rot1i * ii[1]) + (rot2r * ir[2] - rot2i * ii[2]);
    double t2i = ii[0] + (rot1r * ii[1] + rot1i * ir[1]) + (rot2r * ii[2] + rot2i * ir[2]);
    double phaseBalance = Math.hypot(t1r, t1i) + Math.hypot(t2r, t2i);

    return new PowerFlowResult(psp, qsp, phaseBalance, delP, delQ);
  }

  protected void setEqualityConstraints(DoubleSolution solution, PowerFlowResult result) {
    for (int k = 0; k < 12; k++) {
      solution.constraints()[k] = EQUALITY_CONSTRAINT_EPSILON - Math.abs(result.delP[k]);
      solution.constraints()[12 + k] = EQUALITY_CONSTRAINT_EPSILON - Math.abs(result.delQ[k]);
    }
  }

  protected static double sum(double[] values) {
    double total = 0;
    for (double value : values) {
      total += value;
    }
    return total;
  }
