package org.uma.jmetal.algorithm.multiobjective.ctaea;

import java.util.ArrayList;
import java.util.List;
import org.uma.jmetal.algorithm.Algorithm;
import org.uma.jmetal.algorithm.multiobjective.ctaea.util.CTAEATournamentSelection;
import org.uma.jmetal.algorithm.multiobjective.ctaea.util.ConvergenceArchiveUpdate;
import org.uma.jmetal.algorithm.multiobjective.ctaea.util.DiversityArchiveUpdate;
import org.uma.jmetal.algorithm.multiobjective.ctaea.util.MatingProportions;
import org.uma.jmetal.algorithm.multiobjective.ctaea.util.UniformWeightVectors;
import org.uma.jmetal.operator.crossover.CrossoverOperator;
import org.uma.jmetal.operator.mutation.MutationOperator;
import org.uma.jmetal.operator.selection.SelectionOperator;
import org.uma.jmetal.problem.Problem;
import org.uma.jmetal.solution.Solution;
import org.uma.jmetal.util.errorchecking.Check;
import org.uma.jmetal.util.evaluator.SolutionListEvaluator;
import org.uma.jmetal.util.pseudorandom.JMetalRandom;

/**
 * C-TAEA, the two-archive evolutionary algorithm for constrained multi-objective optimization
 * described in:
 *
 * <p>K. Li, R. Chen, G. Fu and X. Yao, "Two-Archive Evolutionary Algorithm for Constrained
 * Multiobjective Optimization", IEEE Transactions on Evolutionary Computation 23(2):303-315,
 * 2019, https://doi.org/10.1109/TEVC.2018.2855411.
 *
 * <p>This implementation follows the one of PlatEMO (class {@code CTAEA} and functions {@code
 * MatingSelection}, {@code UpdateCA} and {@code UpdateDA}). The algorithm keeps two archives of
 * N solutions, where N is the number of weight vectors generated by {@link UniformWeightVectors}
 * from the requested population size (91 for 100 and three objectives):
 *
 * <ul>
 *   <li>the convergence archive (CA), driven by feasibility and convergence ({@link
 *       ConvergenceArchiveUpdate});
 *   <li>the diversity archive (DA), which ignores the constraints and keeps solutions in the
 *       subregions where the CA has few of them ({@link DiversityArchiveUpdate}).
 * </ul>
 *
 * <p>The initial population, of N random solutions, is the offspring of the first update of both
 * archives. In every generation, N offspring are created, one per weight vector: the first
 * parent comes from the CA if the proportion of non-dominated solutions of the union of both
 * archives that belong to the CA (Pc) is larger than the one of the DA (Pd), and from the DA
 * otherwise; the second parent comes from the CA with a probability equal to the proportion of
 * non-dominated solutions of the CA (PC), and from the DA otherwise (see {@link
 * MatingProportions}). Each parent is the winner of a binary tournament in its archive ({@link
 * CTAEATournamentSelection}). The offspring is the first child of the crossover of both parents,
 * mutated (as the {@code OperatorGAhalf} function of PlatEMO). The offspring is evaluated, and
 * the CA and then the DA are updated. The algorithm stops when the number of evaluations reaches
 * the maximum, checked after each generation (hence it may be exceeded by up to N - 1
 * evaluations, as in PlatEMO). The result is the CA.
 *
 * <p>Where PlatEMO and the paper differ, this implementation follows PlatEMO:
 *
 * <ul>
 *   <li>The probability of taking the second parent from the CA is the proportion of
 *       non-dominated solutions of the CA sorted alone (PC); in Algorithm 4 of the paper, it is
 *       the proportion of non-dominated solutions of the union that belong to the CA (Pc), the
 *       same value that chooses the archive of the first parent.
 *   <li>The solutions are associated with the subregions on their raw objectives, except in the
 *       truncation of the feasible solutions of the CA, where the objectives are normalized; the
 *       paper normalizes the objectives (Eq. 8) before every association (Eq. 7).
 *   <li>The ideal point of each Tchebycheff function is the one of the set where it is applied
 *       (the closest solutions of the most crowded subregion, the infeasible candidates of the
 *       CA, or the non-dominated candidates of a subregion of the DA).
 *   <li>Ties are broken by taking the first solution instead of at random.
 *   <li>When both solutions of a tournament are infeasible, the winner is a third random
 *       solution of the archive instead of one of the two at random (with the same distribution).
 * </ul>
 *
 * <p>Differences with PlatEMO:
 *
 * <ul>
 *   <li>The constraints follow the convention of jMetal (a value is satisfied when it is not
 *       negative); the constraint violation of a solution is the absolute value of its overall
 *       constraint violation degree, and a solution is feasible when it is zero.
 *   <li>The offspring of a generation are evaluated together, with a {@link
 *       SolutionListEvaluator}, instead of one by one; the result is the same because no
 *       offspring is used before the update of the archives.
 *   <li>The crossover and mutation operators are given by the user. With jMetal's {@code
 *       SBXCrossover} and {@code PolynomialMutation} (the defaults of PlatEMO are a crossover
 *       probability of 1.0, a mutation probability of 1/n and distribution indexes of 20), the
 *       operators are not identical to PlatEMO's: for instance, jMetal's SBX is the bounded
 *       version and exchanges the two children at random.
 *   <li>The {@code setdiff} function of MATLAB sorts the archive, while this implementation keeps
 *       the order of the solutions; it only affects the ties.
 * </ul>
 *
 * <p>The CA may contain dominated solutions, and infeasible ones if fewer than N feasible
 * solutions have been found.
 *
 * @param <S> the type of the solutions
 */
@SuppressWarnings("serial")
public class CTAEA<S extends Solution<?>> implements Algorithm<List<S>> {
  private final Problem<S> problem;
  private final int maxEvaluations;
  private final CrossoverOperator<S> crossoverOperator;
  private final MutationOperator<S> mutationOperator;
  private final SolutionListEvaluator<S> evaluator;
  private final double[][] weights;
  private final SelectionOperator<List<S>, S> tournament;
  private final ConvergenceArchiveUpdate<S> convergenceArchiveUpdate;
  private final DiversityArchiveUpdate<S> diversityArchiveUpdate;

  private List<S> convergenceArchive;
  private List<S> diversityArchive;
  private int evaluations;

  /**
   * Creates the algorithm.
   *
   * @param problem the problem to solve (at least two objectives)
   * @param populationSize the requested number of weight vectors; the population size is the
   *     number of vectors actually generated, see {@link UniformWeightVectors}
   * @param maxEvaluations the maximum number of evaluations
   * @param crossoverOperator a crossover of two parents; only its first child is used
   * @param mutationOperator the mutation applied to the child
   * @param evaluator the evaluator of the solutions
   */
  public CTAEA(
      Problem<S> problem,
      int populationSize,
      int maxEvaluations,
      CrossoverOperator<S> crossoverOperator,
      MutationOperator<S> mutationOperator,
      SolutionListEvaluator<S> evaluator) {
    Check.notNull(problem, "problem");
    Check.notNull(crossoverOperator, "crossoverOperator");
    Check.notNull(mutationOperator, "mutationOperator");
    Check.notNull(evaluator, "evaluator");
    Check.that(
        problem.numberOfObjectives() >= 2, "The problem must have at least two objectives");
    Check.that(populationSize >= 1, "The population size must be at least 1: " + populationSize);
    Check.that(
        maxEvaluations >= 1,
        "The maximum number of evaluations must be at least 1: " + maxEvaluations);
    Check.that(
        crossoverOperator.numberOfRequiredParents() == 2,
        "The crossover must require two parents");

    this.problem = problem;
    this.maxEvaluations = maxEvaluations;
    this.crossoverOperator = crossoverOperator;
    this.mutationOperator = mutationOperator;
    this.evaluator = evaluator;
    this.weights = UniformWeightVectors.generate(populationSize, problem.numberOfObjectives());
    this.tournament = new CTAEATournamentSelection<>();
    this.convergenceArchiveUpdate = new ConvergenceArchiveUpdate<>(weights);
    this.diversityArchiveUpdate = new DiversityArchiveUpdate<>(weights);
    this.convergenceArchive = new ArrayList<>();
    this.diversityArchive = new ArrayList<>();
  }

  @Override
  public void run() {
    List<S> population = new ArrayList<>(weights.length);
    for (int i = 0; i < weights.length; i++) {
      population.add(problem.createSolution());
    }
    population = evaluator.evaluate(population, problem);
    evaluations = population.size();

    convergenceArchive = convergenceArchiveUpdate.update(new ArrayList<>(), population);
    diversityArchive =
        diversityArchiveUpdate.update(convergenceArchive, new ArrayList<>(), population);

    while (evaluations < maxEvaluations) {
      List<S> offspring = evaluator.evaluate(reproduction(), problem);
      evaluations += offspring.size();

      convergenceArchive = convergenceArchiveUpdate.update(convergenceArchive, offspring);
      diversityArchive =
          diversityArchiveUpdate.update(convergenceArchive, diversityArchive, offspring);
    }
  }

  /** Creates one offspring per weight vector with the restricted mating selection. */
  private List<S> reproduction() {
    MatingProportions proportions = MatingProportions.of(convergenceArchive, diversityArchive);
    boolean firstParentFromConvergenceArchive =
        proportions.convergenceShare() > proportions.diversityShare();
    JMetalRandom random = JMetalRandom.getInstance();

    List<S> offspring = new ArrayList<>(weights.length);
    for (int i = 0; i < weights.length; i++) {
      S firstParent =
          tournament.execute(
              firstParentFromConvergenceArchive ? convergenceArchive : diversityArchive);
      boolean secondParentFromConvergenceArchive =
          random.nextDouble() < proportions.nonDominatedShareOfConvergenceArchive();
      S secondParent =
          tournament.execute(
              secondParentFromConvergenceArchive ? convergenceArchive : diversityArchive);

      List<S> children = crossoverOperator.execute(List.of(firstParent, secondParent));
      offspring.add(mutationOperator.execute(children.get(0)));
    }
    return offspring;
  }

  /**
   * Returns the convergence archive (CA) at the end of the run.
   *
   * @return a copy of the list of solutions of the CA (empty before running the algorithm)
   */
  @Override
  public List<S> result() {
    return new ArrayList<>(convergenceArchive);
  }

  /**
   * Returns the diversity archive (DA).
   *
   * @return a copy of the list of solutions of the DA (empty before running the algorithm)
   */
  public List<S> diversityArchive() {
    return new ArrayList<>(diversityArchive);
  }

  /**
   * Returns the weight vectors, whose number is the population size.
   *
   * @return a copy of the weight vectors
   */
  public double[][] weightVectors() {
    double[][] copy = new double[weights.length][];
    for (int i = 0; i < weights.length; i++) {
      copy[i] = weights[i].clone();
    }
    return copy;
  }

  /**
   * Returns the population size: the number of weight vectors, which is also the size of each
   * archive and the number of offspring per generation.
   *
   * @return the population size
   */
  public int populationSize() {
    return weights.length;
  }

  /**
   * Returns the number of evaluations performed.
   *
   * @return the number of evaluations
   */
  public int evaluations() {
    return evaluations;
  }

  @Override
  public String name() {
    return "C-TAEA";
  }

  @Override
  public String description() {
    return "Two-archive evolutionary algorithm for constrained multi-objective optimization";
  }
}
